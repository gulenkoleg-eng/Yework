  <h1 style="font-size:30px">Правила сайту</h1>
  <p>Публікуйте лише реальні вакансії від свого імені або від імені організації, яку ви представляєте. Зазначайте чесну оплату та умови.</p>
  <p>Заборонено: вакансії, що вимагають передоплати від працівника, «роботу» з сумнівними схемами, дискримінаційні вимоги, чужі контакти.</p>
  <p>Кожну вакансію перевіряє модератор. Ми можемо відхилити або зняти оголошення, що порушує правила, і заблокувати акаунт.</p>
  <p>Персональні дані: ваш телефон і email зберігаються в зашифрованому вигляді. Роботодавець бачить ваші контакти лише тоді, коли ви самі відгукнулися на його вакансію.</p>
